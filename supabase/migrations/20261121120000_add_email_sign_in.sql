-- Adds email sign-in with one-time codes: the ws_email_codes table and the "email" identity provider.

CREATE TABLE ws_email_codes (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         varchar(254) NOT NULL CHECK (email = lower(email)),
    -- HMAC-SHA256 of the code keyed with the backend secret; the code itself is never stored.
    code_hash     varchar(64)  NOT NULL,
    attempt_count integer      NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    created_at    timestamptz  NOT NULL DEFAULT now(),
    expires_at    timestamptz  NOT NULL,
    consumed_at   timestamptz,
    CONSTRAINT ck_ws_email_codes_expires_after_created CHECK (expires_at > created_at)
);
CREATE INDEX idx_ws_email_codes_email ON ws_email_codes (email);

ALTER TABLE ws_email_codes ENABLE ROW LEVEL SECURITY;
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
        REVOKE ALL ON public.ws_email_codes FROM anon, authenticated;
    END IF;
END $$;

ALTER TABLE ws_oauth_accounts DROP CONSTRAINT IF EXISTS ws_oauth_accounts_provider_check;
ALTER TABLE ws_oauth_accounts
    ADD CONSTRAINT ck_ws_oauth_accounts_provider CHECK (provider IN ('google', 'github', 'email'));
